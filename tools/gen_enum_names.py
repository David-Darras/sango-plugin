"""Writes the names of the values of some enums, for WithArray().

The pages of the overlay show the name of a value instead of its number. This
tool reads the enums of the library and writes
lib/include/ui/page/enum_names.h and lib/src/ui/page/enum_names.cc.

  python tools/gen_enum_names.py

Run it again when an enum changes. The names come from the names of the
values: kMirageIsland2 becomes "Mirage Island 2". A value without a name
becomes "<Prefix> <number>".
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import music_names

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The Bulbapedia titles of some enums (see music_names.py).
OVERRIDES = {"BackgroundMusicId": music_names.ORAS}

# (array name, header, enum name, number of values, prefix of an unnamed
# value, game). The game is "XY", "ORAS" or None (both games).
ENUMS = [
    ("kBackgroundMusicNames", "lib/include/system/constant/background_music_xy.h",
     "BackgroundMusicId", 180, "Music", "XY"),
    ("kBackgroundMusicNames", "lib/include/system/constant/background_music.h",
     "BackgroundMusicId", 216, "Music", "ORAS"),
    ("kModelNames", "lib/include/overworld/constant/model.h", "ModelId", 0x162,
     "Model", None),
]

TITLE = re.compile(r"^\s*k\w+\s*=\s*(\d+),\s*///<\s*(.+?)\s*$")

LINE = re.compile(r"^\s*k(\w+)\s*(?:=\s*([^,/]+?))?\s*,")


def read_enum(path, enum_name):
  text = open(os.path.join(REPO, path), encoding="utf-8").read()
  start = text.index("enum class %s" % enum_name)
  body = text[text.index("{", start):text.index("};", start)]
  values = {}
  next_value = 0
  for line in body.splitlines():
    match = LINE.match(line)
    if not match:
      continue
    name, value = match.groups()
    if value is not None:
      value = value.strip()
      if "GAME_CONSTANT" in value or name in ("Count", "LastCharacter"):
        continue
      next_value = int(value, 0)
    elif name == "Count":
      continue
    values.setdefault(next_value, name)
    next_value += 1
  return values


def read_titles(path):
  """Returns the titles that a header gives in the comments of its values."""
  titles = {}
  for line in open(os.path.join(REPO, path), encoding="utf-8"):
    match = TITLE.match(line)
    if match and not line.lstrip().startswith("kDefault"):
      titles.setdefault(int(match.group(1)), match.group(2))
  return titles


def pretty(name):
  words = re.findall(r"[A-Z][a-z]+|[A-Z]+(?![a-z])|\d+|[a-z]+", name)
  return " ".join(words)


def main():
  header = ["// Generated by tools/gen_enum_names.py. Do not edit.", "",
            "#pragma once", "", '#include "common.h"', "", "namespace ui {",
            ""]
  source = ["// Generated by tools/gen_enum_names.py. Do not edit.", "",
            '#include "ui/page/enum_names.h"', "", "namespace ui {", ""]
  for array, path, enum, count, prefix, game in ENUMS:
    values = read_enum(path, enum)
    titles = read_titles(path) if game == "XY" else {}
    condition = {"XY": "#ifdef GAME_XY", "ORAS": "#ifndef GAME_XY"}.get(game)
    if condition:
      header.append(condition)
      source.append(condition)
    header.append("/// The names of %s. The index is the value." % enum)
    header.append("extern const c8* %s[%d];" % (array, count))
    source.append("const c8* %s[%d] = {" % (array, count))
    for i in range(count):
      if i in titles:
        name = titles[i]
      elif i in values:
        name = OVERRIDES.get(enum, {}).get(values[i]) or pretty(values[i])
      else:
        name = "%s %d" % (prefix, i)
      source.append('    "%s",' % name)
    source.append("};")
    if condition:
      header.append("#endif")
      source.append("#endif")
    source.append("")
  header += ["", "} // namespace ui", ""]
  source += ["} // namespace ui", ""]
  with open(os.path.join(REPO, "lib/include/ui/page/enum_names.h"), "w",
            newline="\n") as f:
    f.write("\n".join(header))
  with open(os.path.join(REPO, "lib/src/ui/page/enum_names.cc"), "w",
            newline="\n") as f:
    f.write("\n".join(source))


if __name__ == "__main__":
  main()
